using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static NetMediate.SourceGeneration.Constants;

namespace NetMediate.SourceGeneration;

[Generator]
public sealed class NetMediateRegistrationGenerator : IIncrementalGenerator
{
    private static bool IsGeneratedCodeCoverageEnabled(Compilation compilation)
    {
        var attributeData = compilation.Assembly.GetAttributes()
            .FirstOrDefault(ad => ad.AttributeClass?.ToDisplayString().Replace(GlobalNamespace, "") == "GenDI.GenDICoverationAttribute");

        return attributeData is { ConstructorArguments.Length: 0 }
                || attributeData?.ConstructorArguments[0].Value is not bool includeGeneratedCodeInCoverage
                || includeGeneratedCodeInCoverage;
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var handlerTypes = context
            .SyntaxProvider.CreateSyntaxProvider(
                predicate: static (node, _) => Search(node),
                transform: static (ctx, _) => Transform(ctx)
            )
            .Where(static t => t is not null)
            .Select(static (t, _) => t!)
            .Collect();

        var packageInfo = context.CompilationProvider.Select(
            static (compilation, _) => Selects(compilation)
        );

        var combined = handlerTypes.Combine(packageInfo);

        context.RegisterSourceOutput(
            combined,
            static (sourceProductionContext, input) => Accumulate(sourceProductionContext, input)
        );
    }

    private static void Accumulate(
        SourceProductionContext sourceProductionContext,
        (
            ImmutableArray<INamedTypeSymbol> Left,
            (
                bool hasDiagnostics,
                bool hasResilience,
                bool isNetMediateAssembly,
                string assemblyName,
                bool supportsGlobalUsing,
                string coverage
            ) Right
        ) input
    )
    {
        var (
            types,
            (hasDiagnostics, hasResilience, isNetMediateAssembly, assemblyName, supportsGlobalUsing, coverage)
        ) = input;

        if (supportsGlobalUsing)
        {
            sourceProductionContext.AddSource(
                "NetMediateGlobalUsings.g.cs",
                $"// <auto-generated />\n// Auto-import {assemblyName} so AddNetMediate() is discoverable"
                    + $" without a manual 'using {assemblyName};'.\n"
                    + $"global using {assemblyName};\n"
            );
        }

        if (isNetMediateAssembly || types.IsEmpty)
        {
            // This fallback stub does not flow through the template token replacement path,
            // so the coverage attribute must stay fully qualified here.
            sourceProductionContext.AddSource(
                "NetMediateGeneratedDI.g.cs",
                """
                // <auto-generated />
                [System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
                public static partial class NetMediateGeneratedDI
                {
                    // No handlers found — no registrations to generate.
                }
                """
            );
            return;
        }

        var registrations = BuildRegistrations(types, hasDiagnostics, hasResilience);
        var keyedRegistryBlock = BuildKeyedHandlerRegistries(types);
        var frameworkBehaviors = BuildFrameworkInfrastructure(types);
        var source = BuildSource(registrations, keyedRegistryBlock, frameworkBehaviors, assemblyName, coverage);
        sourceProductionContext.AddSource("NetMediateGeneratedDI.g.cs", source);

        var typedExtensionMethods = BuildTypedExtensionMethods(types);
        var typedExtensionsSource = BuildTypedExtensionsSource(typedExtensionMethods, assemblyName, coverage);
        sourceProductionContext.AddSource("NetMediateTypedExtensions.g.cs", typedExtensionsSource);
    }

    private static (
        bool hasDiagnostics,
        bool hasResilience,
        bool isNetMediateAssembly,
        string assemblyName,
        bool supportsGlobalUsing,
        string coverage
    ) Selects(Compilation compilation)
    {
        var names = compilation.ReferencedAssemblyNames.Select(name => name.Name);
        bool hasDiagnostics = names.Contains("NetMediate.Diagnostics");
        bool hasResilience = names.Contains("NetMediate.Resilience");
        bool isNetMediateAssembly = compilation.AssemblyName?.Replace(GlobalNamespace, "") == PackName;
        bool supportsGlobalUsing =
            compilation is CSharpCompilation { LanguageVersion: >= LanguageVersion.CSharp10 };

        return (
            hasDiagnostics,
            hasResilience,
            isNetMediateAssembly,
            compilation.AssemblyName,
            supportsGlobalUsing,
            IsGeneratedCodeCoverageEnabled(compilation) ? CoverageTpl : string.Empty
        );
    }

    private static bool Search(SyntaxNode node) =>
        node is TypeDeclarationSyntax declaration && declaration.BaseList is not null;

    private static INamedTypeSymbol? Transform(GeneratorSyntaxContext ctx)
    {
        if (ctx.Node is not TypeDeclarationSyntax declaration)
            return null;

        if (ctx.SemanticModel.GetDeclaredSymbol(declaration) is not INamedTypeSymbol typeSymbol)
            return null;

        if (typeSymbol.IsAbstract || typeSymbol.IsGenericType)
            return null;

        if (!IsAccessible(typeSymbol))
            return null;

        return typeSymbol;
    }

    private static (INamedTypeSymbol ifce, string handlerName)[] GetHandlerInterfaces(ImmutableArray<INamedTypeSymbol> types) =>
        [.. types.SelectMany(t => t.AllInterfaces.Select(i => (ifce: i, handlerName: t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))))
            .Where(t => t.ifce.ContainingNamespace.ToDisplayString().Replace(GlobalNamespace, "") == PackName && (
                (t.ifce.OriginalDefinition.Name is RequestHandlerIfce or StreamHandlerIfce && t.ifce.Arity == 2 && t.ifce.TypeArguments.Length == 2) ||
                (t.ifce.OriginalDefinition.Name is CommandHandlerIfce or NotificationHandlerIfce && t.ifce.Arity == 1 && t.ifce.TypeArguments.Length == 1)))];

    /// <summary>
    /// Builds the infrastructure setup lines that go before the generated handler registrations.
    /// For Resilience: registers default option singletons (user may override by registering the
    /// same type before calling <c>AddNetMediate()</c>; <see cref="ServiceCollectionDescriptorExtensions.TryAddSingleton"/>
    /// skips registration when the type is already present).
    /// For Diagnostics: no infrastructure needed — <c>NetMediateDiagnostics</c> is a static class.
    /// </summary>
    private static string BuildFrameworkInfrastructure(ImmutableArray<INamedTypeSymbol> types)
    {
        const string indent = "        ";
        var sb = new StringBuilder();
        var seen = new HashSet<string>(StringComparer.Ordinal);

        foreach (var (ifce, _) in GetHandlerInterfaces(types))
        {
            GetVariables(ifce, out ImmutableArray<ITypeSymbol> args, out bool isTwoArgHandler, out bool isOneArgHandler, out string executorPrefix);
            TwoArgsHandler(indent, sb, seen, args, isTwoArgHandler, executorPrefix);
            OneArgHandler(indent, sb, seen, args, isOneArgHandler, executorPrefix);
        }

        return sb.ToString();
    }

    private static void OneArgHandler(string indent, StringBuilder sb, HashSet<string> seen, ImmutableArray<ITypeSymbol> args, bool isOneArgHandler, string executorPrefix)
    {
        if (isOneArgHandler)
        {
            var line =
                $"{indent}services.TryAddSingleton<{executorPrefix}PipelineExecutor<{args[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}>>();";
            if (seen.Add(line))
                sb.AppendLine(line);
        }
    }

    private static void TwoArgsHandler(string indent, StringBuilder sb, HashSet<string> seen, ImmutableArray<ITypeSymbol> args, bool isTwoArgHandler, string executorPrefix)
    {
        if (isTwoArgHandler)
        {
            var line =
                $"{indent}services.TryAddSingleton<{executorPrefix}PipelineExecutor<{args[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}, {args[1].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}>>();";
            if (seen.Add(line))
                sb.AppendLine(line);
        }
    }

    private static void GetVariables(INamedTypeSymbol ifce, out ImmutableArray<ITypeSymbol> args, out bool isTwoArgHandler, out bool isOneArgHandler, out string executorPrefix)
    {
        var definition = ifce.OriginalDefinition;
        var name = definition.Name;
        var arity = definition.Arity;
        args = ifce.TypeArguments;
        isTwoArgHandler = (name == RequestHandlerIfce || name == StreamHandlerIfce) && arity == 2 && args.Length == 2 && IsAccessible(args[0]) && IsAccessible(args[1]);
        isOneArgHandler = (name == CommandHandlerIfce || name == NotificationHandlerIfce) && arity == 1 && args.Length == 1 && IsAccessible(args[0]);
        executorPrefix = name switch
        {
            RequestHandlerIfce => "Request",
            StreamHandlerIfce => "Stream",
            NotificationHandlerIfce => "Notification",
            _ => "Command"
        };
    }

    /// <summary>
    /// Builds the ordered handler + behavior registrations.
    /// Output order per message-type: Diagnostics behaviors → Resilience behaviors → handler.
    /// Uses insertion-ordered dictionaries for deduplication so the same behavior is never
    /// emitted twice even when multiple handlers share the same message type.
    /// </summary>
    private static IEnumerable<string> BuildRegistrations(
        ImmutableArray<INamedTypeSymbol> types,
        bool hasDiagnostics,
        bool hasResilience
    )
    {
        var diagnosticsBehaviors = new Dictionary<string, bool>();
        var resilienceBehaviors = new Dictionary<string, bool>();
        var handlers = new Dictionary<string, bool>();

        foreach (var handlerType in types)
        {
            BuildRegistration(
                (
                    hasDiagnostics,
                    hasResilience,
                    diagnosticsBehaviors,
                    resilienceBehaviors,
                    handlerType
                )
            );
        }

        var allRegistrations = diagnosticsBehaviors.OrderBy(kv => kv.Key, StringComparer.OrdinalIgnoreCase).Select(kv => kv.Key)
            .Concat(resilienceBehaviors.OrderBy(kv => kv.Key, StringComparer.OrdinalIgnoreCase).Select(kv => kv.Key))
            .Concat(handlers.OrderBy(kv => kv.Key, StringComparer.OrdinalIgnoreCase).Select(kv => kv.Key))
            .Distinct(StringComparer.OrdinalIgnoreCase);

        return allRegistrations;
    }

    /// <summary>
    /// For each distinct handler interface type that has at least one keyed handler
    /// (detected via <c>[Injectable(Key=…)]</c>), generates a consolidated
    /// <c>KeyedHandlerRegistry&lt;THandler&gt;</c> singleton registration.
    /// <para>
    /// Singleton and scoped handlers use <c>Lazy&lt;T&gt;</c> to ensure a single
    /// instance is created. Transient handlers get a fresh instance on every call.
    /// </para>
    /// </summary>
    private static string BuildKeyedHandlerRegistries(ImmutableArray<INamedTypeSymbol> types)
    {
        const string baseIndent = "            ";

        // Map: handlerInterfaceFqn → list of (keyLiteral, lifetime, handlerFqn, ctorArgs)
        var grouped =
            new Dictionary<string, (string handlerIfceFqn, List<(string keyLiteral, int lifetime, string handlerFqn, string ctorArgs)> entries)>(
                StringComparer.Ordinal
            );

        foreach (var handlerType in types)
        {
            var injectableKey = TryGetInjectableKey(handlerType);
            if (injectableKey is null)
                continue;

            var (keyLiteral, lifetime) = injectableKey.Value;

            var handlerFqn = handlerType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var ctorArgs = BuildCtorArgs(handlerType);

            foreach (var @interface in handlerType.AllInterfaces)
            {
                if (!TryGetSupportedHandlerInterfaceFqn(@interface, out var ifceFqn))
                    continue;

                AddKeyedHandlerEntry(
                    grouped,
                    ifceFqn,
                    (keyLiteral, lifetime, handlerFqn, ctorArgs)
                );
            }
        }

        if (grouped.Count == 0)
            return string.Empty;

        var sb = new StringBuilder();
        foreach (var kv in grouped)
        {
            AppendKeyedRegistry(sb, kv.Key, kv.Value.entries, baseIndent);
        }

        return sb.ToString();
    }

    private static void AppendKeyedRegistry(
        StringBuilder sb,
        string ifceFqn,
        List<(string keyLiteral, int lifetime, string handlerFqn, string ctorArgs)> entries,
        string baseIndent
    )
    {
        var inner = baseIndent + "    ";
        var inner2 = inner + "    ";
        var inner3 = inner2 + "    ";
        var inner4 = inner3 + "    ";

        var byKey = GroupEntriesByKey(entries);
        var singletonEntries = GetSingletonEntries(entries);

        var hasSingletons = singletonEntries.Count > 0;

        sb.AppendLine(
            $"{baseIndent}services.AddSingleton<global::NetMediate.KeyedHandlerRegistry<{ifceFqn}>>(static sp =>"
        );
        sb.AppendLine($"{baseIndent}{{");

        // Declare Lazy<T> variables for singleton entries. These capture the outer `sp`
        // (the root/singleton-scope provider) so the singleton instance is created once.
        foreach (var (handlerFqn, ctorArgs) in singletonEntries)
        {
            var lazyVar = BuildLazyVarName(handlerFqn);
            var args = string.IsNullOrEmpty(ctorArgs)
                ? string.Empty
                : BuildCtorArgsWithSp(ctorArgs, "sp");
            sb.AppendLine(
                $"{inner}var {lazyVar} = new global::System.Lazy<{ifceFqn}>(() => new {handlerFqn}({args}));"
            );
        }

        if (hasSingletons)
            sb.AppendLine();

        sb.AppendLine(
            $"{inner}return new global::NetMediate.KeyedHandlerRegistry<{ifceFqn}>("
        );
        sb.AppendLine(
            $"{inner2}new global::System.Collections.Generic.Dictionary<object, global::System.Func<global::System.IServiceProvider, {ifceFqn}>[]>"
        );
        sb.AppendLine($"{inner2}{{");

        AppendKeyedRegistryEntries(sb, byKey, inner3, inner4);

        sb.AppendLine($"{inner2}}});");
        sb.AppendLine($"{baseIndent}}});");
    }

    private static string BuildFactory(
        int lifetime,
        string handlerFqn,
        string ctorArgs
    )
    {
        if (lifetime == 0 /* Singleton */)
        {
            // Singleton: return the value from the Lazy captured in the outer `sp` scope.
            // The `_sp` parameter is ignored because the instance must come from the root scope.
            var lazyVar = BuildLazyVarName(handlerFqn);
            return $"static (_sp) => {lazyVar}.Value";
        }
        else
        {
            // Scoped (1) or Transient (2): create a new instance from the active scope's _sp.
            var args = string.IsNullOrEmpty(ctorArgs)
                ? string.Empty
                : BuildCtorArgsWithSp(ctorArgs, "_sp");
            return $"(_sp) => new {handlerFqn}({args})";
        }
    }

    private static void AddKeyedHandlerEntry(
        Dictionary<
            string,
            (
                string handlerIfceFqn,
                List<(string keyLiteral, int lifetime, string handlerFqn, string ctorArgs)> entries
            )
        > grouped,
        string ifceFqn,
        (string keyLiteral, int lifetime, string handlerFqn, string ctorArgs) entry
    )
    {
        if (!grouped.TryGetValue(ifceFqn, out var group))
        {
            group = (ifceFqn, []);
            grouped[ifceFqn] = group;
        }

        group.entries.Add(entry);
    }

    private static bool TryGetSupportedHandlerInterfaceFqn(
        INamedTypeSymbol @interface,
        out string ifceFqn
    )
    {
        var definition = @interface.OriginalDefinition;
        var namespaceName = definition.ContainingNamespace.ToDisplayString().Replace(GlobalNamespace, "");
        var name = definition.Name;

        if (
            namespaceName == PackName
            && name is CommandHandlerIfce or NotificationHandlerIfce or RequestHandlerIfce or StreamHandlerIfce
        )
        {
            ifceFqn = @interface.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            return true;
        }

        ifceFqn = string.Empty;
        return false;
    }

    private static Dictionary<string, List<(int lifetime, string handlerFqn, string ctorArgs)>> GroupEntriesByKey(
        List<(string keyLiteral, int lifetime, string handlerFqn, string ctorArgs)> entries
    )
    {
        var byKey = new Dictionary<string, List<(int lifetime, string handlerFqn, string ctorArgs)>>(
            StringComparer.Ordinal
        );

        foreach (var (keyLiteral, lifetime, handlerFqn, ctorArgs) in entries)
        {
            if (!byKey.TryGetValue(keyLiteral, out var list))
            {
                list = [];
                byKey[keyLiteral] = list;
            }

            list.Add((lifetime, handlerFqn, ctorArgs));
        }

        return byKey;
    }

    private static List<(string handlerFqn, string ctorArgs)> GetSingletonEntries(
        List<(string keyLiteral, int lifetime, string handlerFqn, string ctorArgs)> entries
    ) =>
        [.. entries
            .Where(e => e.lifetime == 0 /* Singleton */)
            .Select(e => (e.handlerFqn, e.ctorArgs))
            .Distinct()];

    private static void AppendKeyedRegistryEntries(
        StringBuilder sb,
        Dictionary<string, List<(int lifetime, string handlerFqn, string ctorArgs)>> byKey,
        string entryIndent,
        string factoryIndent
    )
    {
        var keyList = byKey.Keys.ToList();
        for (var keyIndex = 0; keyIndex < keyList.Count; keyIndex++)
        {
            var keyLiteral = keyList[keyIndex];
            var handlerList = byKey[keyLiteral];
            var keyComma = keyIndex < keyList.Count - 1 ? "," : string.Empty;

            if (handlerList.Count == 1)
            {
                var (lifetime, handlerFqn, ctorArgs) = handlerList[0];
                var factory = BuildFactory(lifetime, handlerFqn, ctorArgs);
                sb.AppendLine($"{entryIndent}{{ {keyLiteral}, [{factory}] }}{keyComma}");
                continue;
            }

            sb.AppendLine($"{entryIndent}{{ {keyLiteral}, [");
            for (var handlerIndex = 0; handlerIndex < handlerList.Count; handlerIndex++)
            {
                var (lifetime, handlerFqn, ctorArgs) = handlerList[handlerIndex];
                var factory = BuildFactory(lifetime, handlerFqn, ctorArgs);
                var handlerComma = handlerIndex < handlerList.Count - 1 ? "," : string.Empty;
                sb.AppendLine($"{factoryIndent}{factory}{handlerComma}");
            }

            sb.AppendLine($"{entryIndent}] }}{keyComma}");
        }
    }

    /// <summary>
    /// Replaces the service-provider variable name in a pre-built ctor-args string.
    /// The generator builds ctor-args with a placeholder "sp" (the outer singleton factory
    /// parameter); this method swaps it for <paramref name="spVar"/> when the actual
    /// resolution should come from a different provider variable.
    /// </summary>
    private static string BuildCtorArgsWithSp(string ctorArgs, string spVar)
        => ctorArgs.Replace("sp.GetRequiredService", $"{spVar}.GetRequiredService");

    /// <summary>
    /// Returns a safe local variable name for the lazy wrapper of a handler.
    /// </summary>
    private static string BuildLazyVarName(string handlerFqn)
    {
        // Strip "global::" and replace non-identifier chars with underscores
        var name = handlerFqn.Replace("global::", string.Empty);
        var sb = new StringBuilder("lazy_");
        foreach (var c in name)
            sb.Append(char.IsLetterOrDigit(c) ? c : '_');
        return sb.ToString();
    }

    /// <summary>
    /// Generates the constructor argument list for a handler type so that all parameters
    /// are resolved from the service provider (<c>sp</c>). Returns an empty string when
    /// the handler has a public parameterless constructor.
    /// </summary>
    private static string BuildCtorArgs(INamedTypeSymbol handlerType)
    {
        // Pick the public constructor with the most parameters (primary constructor pattern)
        var ctor = handlerType
            .Constructors.Where(c => c.DeclaredAccessibility == Accessibility.Public)
            .OrderByDescending(c => c.Parameters.Length)
            .FirstOrDefault();

        if (ctor is null || ctor.Parameters.Length == 0)
            return string.Empty;

        return string.Join(
            ", ",
            ctor.Parameters.Select(p =>
            {
                var typeFqn = p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                return $"sp.GetRequiredService<{typeFqn}>()";
            })
        );
    }

    /// <summary>
    /// Returns the key literal (as a C# source expression) and the lifetime integer
    /// (Singleton=0, Scoped=1, Transient=2) when the type carries an
    /// <c>[Injectable(Key=…)]</c> attribute with a non-null key; otherwise null.
    /// </summary>
    private static (string keyLiteral, int lifetime)? TryGetInjectableKey(INamedTypeSymbol type)
    {
        foreach (var attr in type.GetAttributes())
        {
            var attrClass = attr.AttributeClass;
            if (attrClass is null)
                continue;

            var attrName = attrClass.OriginalDefinition?.Name ?? attrClass.Name;
            if (attrName != "InjectableAttribute")
                continue;

            // NamedArguments contains Key when set
            var keyArg = attr.NamedArguments.FirstOrDefault(a => a.Key == "Key");
            if (keyArg.Value.IsNull || keyArg.Value.Value is null)
                continue; // no key set

            var keyLiteral = FormatConstantAsLiteral(keyArg.Value);
            if (keyLiteral is null)
                continue;

            // First constructor argument is the ServiceLifetime enum value
            // ServiceLifetime: Singleton=0, Scoped=1, Transient=2
            var lifetime = 0; // default Singleton
            if (
                attr.ConstructorArguments.Length > 0
                && attr.ConstructorArguments[0].Value is int l
            )
                lifetime = l;

            return (keyLiteral, lifetime);
        }

        return null;
    }

    /// <summary>
    /// Converts a <see cref="TypedConstant"/> to its C# source representation.
    /// Handles <see langword="string"/>, <see langword="int"/>, <see langword="bool"/>,
    /// <see langword="char"/>, and other primitive types.
    /// Returns <see langword="null"/> for unsupported constant kinds.
    /// </summary>
    private static string? FormatConstantAsLiteral(TypedConstant constant)
    {
        if (constant.IsNull)
            return null;

        return constant.Value switch
        {
            string s => $"\"{s.Replace("\\", "\\\\").Replace("\"", "\\\"")}\"",
            bool b => b ? "true" : "false",
            char c => $"'{c}'",
            _ => constant.Value?.ToString(),
        };
    }

    private static void BuildRegistration(BuildRegistrationArguments arguments)
    {
        var (
            hasDiagnostics,
            hasResilience,
            diagnosticsBehaviors,
            resilienceBehaviors,
            handlerType
        ) = arguments;

        foreach (var @interface in handlerType.AllInterfaces)
        {
            var definition = @interface.OriginalDefinition;
            if (definition.ContainingNamespace.ToDisplayString().Replace(GlobalNamespace, "") != PackName)
                continue;

            var name = definition.Name;
            var arity = definition.Arity;
            var args = @interface.TypeArguments;

            ProcessHandlerInterface(
                (
                    name,
                    arity,
                    args,
                    hasDiagnostics,
                    hasResilience,
                    diagnosticsBehaviors,
                    resilienceBehaviors
                )
            );
        }
    }

    private static void ProcessHandlerInterface(ProcessHandlerInterfaceArguments arguments)
    {
        if (!TryCreateBehaviorRegistration(arguments, out var registration))
            return;

        AddBehaviorRegistrations(registration);
    }

    private static bool TryCreateBehaviorRegistration(
        ProcessHandlerInterfaceArguments arguments,
        out BehaviorRegistration registration
    )
    {
        var (
            interfaceName,
            arity,
            args,
            hasDiagnostics,
            hasResilience,
            diagnosticsBehaviors,
            resilienceBehaviors
        ) = arguments;

        registration = default;

        if (arity == 1 && args.Length == 1 && IsAccessible(args[0]))
        {
            var msg = args[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            registration = interfaceName switch
            {
                CommandHandlerIfce => new BehaviorRegistration(
                    CommandHandlerIfce,
                    msg,
                    null,
                    hasDiagnostics,
                    hasResilience,
                    diagnosticsBehaviors,
                    resilienceBehaviors
                ),
                NotificationHandlerIfce => new BehaviorRegistration(
                    NotificationHandlerIfce,
                    msg,
                    null,
                    hasDiagnostics,
                    hasResilience,
                    diagnosticsBehaviors,
                    resilienceBehaviors
                ),
                _ => default
            };

            return registration.MessageFqn is not null;
        }

        if (interfaceName == RequestHandlerIfce && arity == 2 && args.Length == 2 && IsAccessible(args[0]) && IsAccessible(args[1]))
        {
            registration = new BehaviorRegistration(
                RequestHandlerIfce,
                args[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                args[1].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                hasDiagnostics,
                hasResilience,
                diagnosticsBehaviors,
                resilienceBehaviors
            );
            return true;
        }

        return false;
    }

    private static void AddBehaviorRegistrations(BehaviorRegistration registration)
    {
        AddBehaviorIfEnabled(
            registration.DiagnosticsBehaviors,
            registration.HasDiagnostics,
            BuildBehaviorRegistration(
                $"{GlobalNamespace}NetMediate.Diagnostics.",
                "Telemetry",
                registration.InterfaceName,
                registration.MessageFqn,
                registration.ResponseFqn
            )
        );

        AddBehaviorIfEnabled(
            registration.ResilienceBehaviors,
            registration.HasResilience,
            BuildBehaviorRegistration(
                $"{GlobalNamespace}NetMediate.Resilience.",
                "Retry",
                registration.InterfaceName,
                registration.MessageFqn,
                registration.ResponseFqn
            )
        );
        AddBehaviorIfEnabled(
            registration.ResilienceBehaviors,
            registration.HasResilience,
            BuildBehaviorRegistration(
                $"{GlobalNamespace}NetMediate.Resilience.",
                "Timeout",
                registration.InterfaceName,
                registration.MessageFqn,
                registration.ResponseFqn
            )
        );
        AddBehaviorIfEnabled(
            registration.ResilienceBehaviors,
            registration.HasResilience,
            BuildBehaviorRegistration(
                $"{GlobalNamespace}NetMediate.Resilience.",
                "CircuitBreaker",
                registration.InterfaceName,
                registration.MessageFqn,
                registration.ResponseFqn
            )
        );
    }

    private static void AddBehaviorIfEnabled(
        Dictionary<string, bool> registrations,
        bool enabled,
        string registration
    )
    {
        if (enabled)
            registrations.AddIfNew(registration);
    }

    private static string BuildBehaviorRegistration(
        string namespacePrefix,
        string behaviorPrefix,
        string interfaceName,
        string messageFqn,
        string? responseFqn
    )
    {
        var behaviorName = interfaceName switch
        {
            CommandHandlerIfce => $"{behaviorPrefix}CommandBehavior<{messageFqn}>",
            NotificationHandlerIfce => $"{behaviorPrefix}NotificationBehavior<{messageFqn}>",
            RequestHandlerIfce when responseFqn is not null =>
                $"{behaviorPrefix}RequestBehavior<{messageFqn}, {responseFqn}>",
            _ => throw new InvalidOperationException(
                $"Unsupported handler interface '{interfaceName}'. Expected one of '{CommandHandlerIfce}', '{NotificationHandlerIfce}', or '{RequestHandlerIfce}'. This indicates an internal generator error."
            )
        };

        return $"services.TryAddSingleton<{namespacePrefix}{behaviorName}>();";
    }

